function createTempEnv() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'novaswarm-v9-'));
  const prev = {
    NOVASWARM_DATA_DIR: process.env.NOVASWARM_DATA_DIR,
    NOVASWARM_AUDIT_JSONL_PATH: process.env.NOVASWARM_AUDIT_JSONL_PATH,
    NOVASWARM_LOGIN_LOCKS_PATH: process.env.NOVASWARM_LOGIN_LOCKS_PATH,
  };
  process.env.NOVASWARM_DATA_DIR = tmpDir;
  process.env.NOVASWARM_AUDIT_JSONL_PATH = path.join(tmpDir, 'audit-chain.jsonl');
  process.env.NOVASWARM_LOGIN_LOCKS_PATH = path.join(tmpDir, '.login-locks.json');
  resetInMemoryStateForTests();
  resetAuthSecurityStateForTests();
  return {
    tmpDir,
    restore() {
      resetInMemoryStateForTests();
      resetAuthSecurityStateForTests();
      for (const [k, v] of Object.entries(prev)) {
        if (v === undefined) delete process.env[k];
        else process.env[k] = v;
      }
      fs.rmSync(tmpDir, { recursive: true, force: true });
    },
  };
}

test('9a: skill automated unit test gate rejects failing assertion and approves passing assertion', () => {
  const env = createTempEnv();
  const createdFiles: string[] = [];
  try {
    const badSkill = createAndValidateSkill({
      name: 'BuggyMathSkill',
      description: 'Hibás tesztű skill',
      code: 'export function run(x) { return Number(x) * 2; }',
      testCode: 'if (run(3) !== 999) { throw new Error("Assertion failed: expected 999"); }',
      createdByAgentId: 'tester',
    });
    createdFiles.push(path.join(process.cwd(), badSkill.filePath));
    assert.equal(badSkill.testPassed, false);
    assert.equal(badSkill.status, 'rejected');
    assert.match(badSkill.testReport || '', /ELBUKOTT/);

    const fixed = runSkillSelfTest(badSkill.id, 'if (run(3) !== 6) { throw new Error("unexpected"); }');
    assert.ok(fixed);
    assert.equal(fixed.testPassed, true);
    assert.equal(fixed.status, 'verified');
    assert.match(fixed.testReport || '', /SIKERES/);
  } finally {
    for (const f of createdFiles) {
      if (fs.existsSync(f)) fs.unlinkSync(f);
    }
    env.restore();
  }
});

test('9b: weekly self-evaluation benchmark tracks cost, solved/failed items, creates Kanban goals, and notifies Telegram', async () => {
  const env = createTempEnv();
  const sentMessages: string[] = [];
  try {
    updateState((s) => {
      s.settings.telegramChatId = '123456';
      s.settings.telegramHasToken = true;
      s.settings.dailySpendUsd = 0.42;
      s.goalCycles = [
        ...(s.goalCycles || []),
        {
          id: 'gc-ok',
          goal: 'Log elemzés javítva',
          phase: 'completed',
          verifiedSuccess: true,
          createdAt: new Date().toISOString(),
        },
        {
          id: 'gc-fail',
          goal: 'DNS cache hiba elhárítása',
          phase: 'failed',
          verifiedSuccess: false,
          criticFeedback: 'timeout',
          createdAt: new Date().toISOString(),
        },
      ];
      const nowIso = new Date().toISOString();
      s.kanban.push({
        id: 'k-done',
        title: 'Régi kártya',
        description: 'Kész',
        status: 'done',
        assignedAgentId: null,
        priority: 'medium',
        createdAt: nowIso,
        updatedAt: nowIso,
      });
      s.auditLogs.push({
        id: 'a1',
        timestamp: new Date().toISOString(),
        type: 'action',
        sourceAgentId: 'ag1',
        sourceAgentName: 'Teszt Ágens',
        message: 'Sikeres diagnosztika',
        verifiedExecution: true,
      });
    });

    const report = await runWeeklySelfEvaluationBenchmark({
      telegramSender: async (text) => {
        sentMessages.push(text);
        return { ok: true };
      },
    });

    assert.equal(report.totalSpendUsd, 0.42);
    assert.ok((report.solvedItems || []).some((x) => x.includes('Log elemzés')));
    assert.ok((report.failedItems || []).some((x) => x.includes('DNS cache hiba')));
    assert.ok(report.autoGeneratedGoals && report.autoGeneratedGoals.length >= 1);

    const todoCards = getState().kanban.filter((k) => k.status === 'todo');
    assert.ok(todoCards.some((k) => k.title.startsWith('Fejlesztési cél:')));
    assert.equal(sentMessages.length, 1);
    assert.match(sentMessages[0], /Heti Önértékelés/);
  } finally {
    env.restore();
  }
});

test('9c: MCP telemetry, autonomous discovery from capability catalog, ROI verdict and failing auto-disable', async () => {
  const env = createTempEnv();
  try {
    const discovered = await autonomousDiscoverAndInstallMcp({
      capabilityQuery: 'home automation hass mqtt',
      autoTest: false,
      catalogItems: [
        {
          name: 'Home Assistant MCP',
          endpointUrl: 'http://192.168.1.50:8123/mcp',
          authType: 'none',
          kind: 'mcp',
          capabilities: ['home', 'hass', 'mqtt', 'automation'],
          description: 'Helyi okosotthon MCP',
        },
        {
          name: 'Unrelated Weather',
          endpointUrl: 'http://192.168.1.60:9000/mcp',
          authType: 'none',
          kind: 'mcp',
          description: 'Időjárás MCP',
          capabilities: ['weather'],
        },
      ],
    });
    assert.equal(discovered.installed.length, 1);
    const haMcp = discovered.installed[0];
    assert.equal(haMcp.name, 'Home Assistant MCP');
    assert.equal(haMcp.autoDiscovered, true);

    // Record successful calls on discovered server -> worth_it
    recordMcpCallOutcome(haMcp.id, true, 120);
    recordMcpCallOutcome(haMcp.id, true, 80);

    // Add a chronically failing server -> low_value + auto-disabled
    updateState((s) => {
      s.mcpServers.push({
        id: 'mcp-broken',
        name: 'Törött MCP',
        description: 'Hibás teszt szerver',
        endpointUrl: 'http://192.168.1.99:9999/mcp',
        transport: 'http',
        authType: 'none',
        hasCredentials: false,
        oauthConfigured: false,
        status: 'error',
        enabled: true,
        lastCheckedAt: null,
        lastCheckMessage: 'Hiba',
      });
    });
    recordMcpCallOutcome('mcp-broken', false, 500);
    recordMcpCallOutcome('mcp-broken', false, 600);
    recordMcpCallOutcome('mcp-broken', false, 700);

    const roi = await evaluateMcpRoiAndDiscover({});
    const healthy = getState().mcpServers.find((m) => m.id === haMcp.id);
    const broken = getState().mcpServers.find((m) => m.id === 'mcp-broken');
    assert.equal(healthy?.roiVerdict, 'worth_it');
    assert.equal(broken?.roiVerdict, 'low_value');
    assert.equal(broken?.enabled, false);
    assert.equal(roi.disabledLowValueIds.includes('mcp-broken'), true);
  } finally {
    env.restore();
  }
});
